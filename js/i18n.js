var i18n = (function () {
  var STORAGE_KEY = 'wifi-qr.lang';
  var current = 'en';

  function detect() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && I18N[saved]) { return saved; }
    } catch (e) { /* storage may be unavailable */ }
    var candidates = navigator.languages || [navigator.language || 'en'];
    for (var i = 0; i < candidates.length; i++) {
      var code = String(candidates[i]).toLowerCase().split('-')[0];
      if (I18N[code]) { return code; }
    }
    return 'en';
  }

  function t(key) {
    var table = I18N[current] || I18N.en;
    return table[key] || I18N.en[key] || key;
  }

  function apply(lang) {
    if (I18N[lang]) { current = lang; }
    try { localStorage.setItem(STORAGE_KEY, current); } catch (e) { /* ignore */ }
    document.documentElement.lang = current;
    document.title = t('appName') + ' · wifi-qr';
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
    }
    var phNodes = document.querySelectorAll('[data-i18n-ph]');
    for (var j = 0; j < phNodes.length; j++) {
      phNodes[j].setAttribute('placeholder', t(phNodes[j].getAttribute('data-i18n-ph')));
    }
    var ariaNodes = document.querySelectorAll('[data-i18n-aria]');
    for (var k = 0; k < ariaNodes.length; k++) {
      ariaNodes[k].setAttribute('aria-label', t(ariaNodes[k].getAttribute('data-i18n-aria')));
    }
  }

  return { detect: detect, apply: apply, t: t, get lang() { return current; } };
})();
